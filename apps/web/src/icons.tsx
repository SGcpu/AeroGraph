/**
 * Renders a clean vector SVG icon corresponding to any canonical TraceEventKind.
 */
export function EventKindIcon({
  kind,
  size = 14,
  color = "currentColor"
}: {
  kind: string;
  size?: number;
  color?: string;
}) {
  switch (kind) {
    case "prompt":
      return <MessageSquareIcon size={size} color={color} />;
    case "response":
      return <SparklesIcon size={size} color={color} />;
    case "tool_call":
      return <ToolIcon size={size} color={color} />;
    case "tool_result":
      return <BoxIcon size={size} color={color} />;
    case "error":
      return <AlertTriangleIcon size={size} color={color} />;
    case "handoff":
      return <GitBranchIcon size={size} color={color} />;
    case "note":
      return <FileTextIcon size={size} color={color} />;
    case "state_snapshot":
      return <StateIcon size={size} color={color} />;
    case "retriever":
      return <RetrieverIcon size={size} color={color} />;
    case "checkpoint":
      return <CheckpointIcon size={size} color={color} />;
    default:
      return <LayersIcon size={size} color={color} />;
  }
}
